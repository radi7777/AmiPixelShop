void icon(LONG x, LONG y, LONG id, ULONG c)
{
    LONG i, j;
    ULONG half = 0xFF000000 | (((c & 0xFEFEFE) >> 1) + ((COL_BAR & 0xFEFEFE) >> 1));
    for (j = 0; j < 16; j++)
        for (i = 0; i < 16; i++) {
            char ch = icons[id][j][i];
            if (ch == '#')
                pset(x + i, y + j, c);
            else if (ch == '+')
                pset(x + i, y + j, half);
        }
}

/* ---- Blit Backbuffer -> VRAM ----
 * Bewusst nur ueber p96WritePixelArray: P96 sperrt selbst. Direktes
 * p96LockBitMap aus unserem Task hat sich zusammen mit anderen Tasks, die
 * den Bildschirm lesen (Screengrabber), auf Emu68 aufgehaengt - und war im
 * Benchmark nicht schneller (167 vs. 178 fps Vollbild). */
void blit(LONG x, LONG y, LONG w, LONG h)
{
    struct RenderInfo ri;

    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > SW) w = SW - x;
    if (y + h > SH) h = SH - y;
    if (w <= 0 || h <= 0)
        return;
    ri.Memory = bb;
    ri.BytesPerRow = SW * 4;
    ri.pad = 0;
    ri.RGBFormat = RGBFB_A8R8G8B8;
    p96WritePixelArray(&ri, x, y, win->RPort, x, y, w, h);
}

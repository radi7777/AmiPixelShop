static LONG clx0, cly0, clx1, cly1;

ULONG now_us(void)
{
    struct timeval tv;
    GetSysTime(&tv);
    return tv.tv_secs * 1000000UL + tv.tv_micro;
}

void gfx_clip(LONG x0, LONG y0, LONG x1, LONG y1)
{
    clx0 = x0 < 0 ? 0 : x0;
    cly0 = y0 < 0 ? 0 : y0;
    clx1 = x1 > SW ? SW : x1;
    cly1 = y1 > SH ? SH : y1;
}

void gfx_noclip(void)
{
    gfx_clip(0, 0, SW, SH);
}

void fill(LONG x, LONG y, LONG w, LONG h, ULONG c)
{
    LONG x1 = x + w, y1 = y + h, i, j;
    if (x < clx0) x = clx0;
    if (y < cly0) y = cly0;
    if (x1 > clx1) x1 = clx1;
    if (y1 > cly1) y1 = cly1;
    for (j = y; j < y1; j++) {
        ULONG *p = bb + j * SW;
        for (i = x; i < x1; i++)
            p[i] = c;
    }
}

void frame(LONG x, LONG y, LONG w, LONG h, ULONG c)
{
    fill(x, y, w, 1, c);
    fill(x, y + h - 1, w, 1, c);
    fill(x, y, 1, h, c);
    fill(x + w - 1, y, 1, h, c);
}

void pset(LONG x, LONG y, ULONG c)
{
    if (x >= clx0 && x < clx1 && y >= cly0 && y < cly1)
        bb[y * SW + x] = c;
}

void line(LONG x0, LONG y0, LONG x1, LONG y1, ULONG c)
{
    LONG dx = x1 > x0 ? x1 - x0 : x0 - x1, sx = x0 < x1 ? 1 : -1;
    LONG dy = y1 > y0 ? y0 - y1 : y1 - y0, sy = y0 < y1 ? 1 : -1;
    LONG err = dx + dy, e2;
    for (;;) {
        pset(x0, y0, c);
        if (x0 == x1 && y0 == y1)
            break;
        e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

/* Linie im Ameisenmuster (schwarz/weiss, diagonal laufend) */
void ant_line(LONG x0, LONG y0, LONG x1, LONG y1, LONG phase)
{
    LONG dx = x1 > x0 ? x1 - x0 : x0 - x1, sx = x0 < x1 ? 1 : -1;
    LONG dy = y1 > y0 ? y0 - y1 : y1 - y0, sy = y0 < y1 ? 1 : -1;
    LONG err = dx + dy, e2;
    for (;;) {
        pset(x0, y0, (((x0 + y0 + phase) >> 2) & 1) ? 0xFF000000 : 0xFFFFFFFF);
        if (x0 == x1 && y0 == y1)
            break;
        e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

void circle(LONG cx, LONG cy, LONG r, ULONG c)
{
    LONG x = r, y = 0, err = 1 - r;
    if (r <= 0) {
        pset(cx, cy, c);
        return;
    }
    while (x >= y) {
        pset(cx + x, cy + y, c); pset(cx - x, cy + y, c);
        pset(cx + x, cy - y, c); pset(cx - x, cy - y, c);
        pset(cx + y, cy + x, c); pset(cx - y, cy + x, c);
        pset(cx + y, cy - x, c); pset(cx - y, cy - x, c);
        y++;
        if (err < 0)
            err += 2 * y + 1;
        else {
            x--;
            err += 2 * (y - x) + 1;
        }
    }
}


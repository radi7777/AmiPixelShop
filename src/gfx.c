/* UTF-8 -> Latin-1 (nur 2-Byte-Folgen, reicht fuer Umlaute) */
static ULONG next_char(const UBYTE **sp)
{
    const UBYTE *s = *sp;
    ULONG c = *s++;
    if ((c & 0xE0) == 0xC0 && (*s & 0xC0) == 0x80) {
        c = ((c & 0x1F) << 6) | (*s++ & 0x3F);
        if (c > 255)
            c = '?';
    } else if (c >= 0x80) {
        /* laengere Folge: ueberspringen, Gedankenstrich als '-' */
        ULONG u = (c & 0xF0) == 0xE0 ? (c & 0x0F) : (c & 0x07);
        LONG n = (c & 0xF0) == 0xE0 ? 2 : (c & 0xF8) == 0xF0 ? 3 : 0, i;
        for (i = 0; i < n && (*s & 0xC0) == 0x80; i++)
            u = (u << 6) | (*s++ & 0x3F);
        c = (u == 0x2013 || u == 0x2014 || u == 0x2212) ? '-' : '?';
    }
    *sp = s;
    return c;
}

static LONG draw_text(LONG x, LONG y, const char *str, ULONG col,
                      const Glyph *gl, const UBYTE *alpha)
{
    const UBYTE *s = (const UBYTE *)str;
    ULONG crb = col & 0xFF00FF, cg = col & 0x00FF00;
    while (*s) {
        ULONG c = next_char(&s);
        const Glyph *g = &gl[c];
        LONG gx = x + g->xo, gy = y + g->yo, i, j;
        const UBYTE *a = alpha + g->off;
        for (j = 0; j < g->h; j++) {
            LONG py = gy + j;
            if (py < cly0 || py >= cly1)
                continue;
            for (i = 0; i < g->w; i++) {
                LONG px = gx + i;
                ULONG av = a[j * g->w + i], d, rb, gg;
                if (!av || px < clx0 || px >= clx1)
                    continue;
                av += av >> 7;
                d = bb[py * SW + px];
                rb = ((crb * av + (d & 0xFF00FF) * (256 - av)) >> 8) & 0xFF00FF;
                gg = ((cg * av + (d & 0x00FF00) * (256 - av)) >> 8) & 0x00FF00;
                bb[py * SW + px] = 0xFF000000 | rb | gg;
            }
        }
        x += g->adv;
    }
    return x;
}

LONG text(LONG x, LONG y, const char *s, ULONG c)
{
    return draw_text(x, y, s, c, fui_glyphs, fui_alpha);
}

LONG text_bold(LONG x, LONG y, const char *s, ULONG c)
{
    return draw_text(x, y, s, c, fbold_glyphs, fbold_alpha);
}

LONG text_width(const char *str)
{
    const UBYTE *s = (const UBYTE *)str;
    LONG w = 0;
    while (*s)
        w += fui_glyphs[next_char(&s)].adv;
    return w;
}

